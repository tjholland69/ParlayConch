-- Loads a league exported by export-league.sql into a LOCAL database, as a
-- copy to test against. Never run this against production.
--
--   psql postgres://localhost/parlayconch -v ON_ERROR_STOP=1 \
--     -v json_file=kirk.json -f scripts/sql/import-league.sql
--
-- The copy arrives as a new league named "<name> (seed copy)", flagged as
-- demo. Its members become new local demo accounts ("seed-<league>-1", ...)
-- with made-up @example.com emails and no password, so nothing local can
-- email or sign in as a real person. Use Act For as a super user to look
-- around as one of them. Weeks and games are matched to the ones already
-- here (by season and week number, then by matchup) and created if missing.
-- Parlays and legs get new ids. Run it twice and it stops rather than
-- loading a second copy: delete the "(seed copy)" league first to reload.

\set content `cat :json_file`

BEGIN;

CREATE TEMP TABLE _in ON COMMIT DROP AS SELECT :'content'::jsonb AS doc;

DO $$
BEGIN
  IF (SELECT doc->'league' IS NULL OR jsonb_typeof(doc->'league') <> 'object' FROM _in) THEN
    RAISE EXCEPTION 'That file has no league in it. Was the export empty (league name not found)?';
  END IF;
  IF EXISTS (SELECT 1 FROM leagues, _in WHERE leagues.name = (doc->'league'->>'name') || ' (seed copy)') THEN
    RAISE EXCEPTION 'A seed copy of this league is already here. Delete it first to load a fresh one.';
  END IF;
END $$;

CREATE TEMP TABLE _league ON COMMIT DROP AS
SELECT (doc->'league'->>'id')::int AS old_id, nextval('leagues_id_seq')::int AS new_id FROM _in;

-- People: new local ids, first names kept, everything else left behind.
CREATE TEMP TABLE _users ON COMMIT DROP AS
SELECT u->>'id' AS old_id,
       'seed-' || (SELECT new_id FROM _league) || '-' || row_number() OVER (ORDER BY u->>'id') AS new_id,
       u->>'first_name' AS first_name,
       u->>'display_name' AS display_name
FROM _in, jsonb_array_elements(doc->'users') AS u;

INSERT INTO users (id, email, first_name, is_demo, settings)
SELECT new_id,
       new_id || '@example.com',
       COALESCE(first_name, display_name, 'Member'),
       true,
       CASE WHEN display_name IS NOT NULL THEN jsonb_build_object('displayName', display_name) END
FROM _users;

INSERT INTO leagues
SELECT (jsonb_populate_record(NULL::leagues, doc->'league' || jsonb_build_object(
  'id', (SELECT new_id FROM _league),
  'name', (doc->'league'->>'name') || ' (seed copy)',
  'invite_code', 'SEED' || upper(substr(md5(random()::text), 1, 8)),
  'is_demo', true,
  'use_demo_week_data', false
))).*
FROM _in;

INSERT INTO league_members
SELECT (jsonb_populate_record(NULL::league_members, m || jsonb_build_object(
  'id', nextval('league_members_id_seq'),
  'league_id', (SELECT new_id FROM _league),
  'user_id', (SELECT new_id FROM _users WHERE old_id = m->>'user_id')
))).*
FROM _in, jsonb_array_elements(doc->'members') AS m;

-- Weeks: use the local one for that season and week number, else add it.
INSERT INTO weeks (season, week_number, label, is_active)
SELECT (w->>'season')::int, (w->>'week_number')::int, w->>'label', false
FROM _in, jsonb_array_elements(doc->'weeks') AS w
ON CONFLICT (season, week_number) DO NOTHING;

CREATE TEMP TABLE _weeks ON COMMIT DROP AS
SELECT (w->>'id')::int AS old_id, weeks.id AS new_id
FROM _in, jsonb_array_elements(doc->'weeks') AS w
JOIN weeks ON weeks.season = (w->>'season')::int AND weeks.week_number = (w->>'week_number')::int;

-- Games: use the local one for that week and matchup, else add it.
INSERT INTO games
SELECT (jsonb_populate_record(NULL::games, g || jsonb_build_object(
  'id', nextval('games_id_seq'),
  'week_id', (SELECT new_id FROM _weeks WHERE old_id = (g->>'week_id')::int)
))).*
FROM _in, jsonb_array_elements(doc->'games') AS g
ON CONFLICT (week_id, home_team, away_team) DO NOTHING;

CREATE TEMP TABLE _games ON COMMIT DROP AS
SELECT (g->>'id')::int AS old_id, games.id AS new_id
FROM _in, jsonb_array_elements(doc->'games') AS g
JOIN _weeks ON _weeks.old_id = (g->>'week_id')::int
JOIN games ON games.week_id = _weeks.new_id AND games.home_team = g->>'home_team' AND games.away_team = g->>'away_team';

-- Parlays. Columns are listed because status_group is generated by the
-- database and can't be inserted. A column this doesn't list keeps its default.
CREATE TEMP TABLE _parlays ON COMMIT DROP AS
SELECT (p->>'id')::int AS old_id, nextval('parlays_id_seq')::int AS new_id, p
FROM _in, jsonb_array_elements(doc->'parlays') AS p;

INSERT INTO parlays (id, user_id, league_id, week_id, status, approved_by, approved_at, created_at, source, boost_pct, actual_odds)
SELECT _parlays.new_id,
       (SELECT new_id FROM _users WHERE old_id = p->>'user_id'),
       (SELECT new_id FROM _league),
       (SELECT new_id FROM _weeks WHERE old_id = (p->>'week_id')::int),
       r.status,
       (SELECT new_id FROM _users WHERE old_id = p->>'approved_by'),
       r.approved_at,
       r.created_at,
       r.source,
       r.boost_pct,
       r.actual_odds
FROM _parlays, jsonb_populate_record(NULL::parlays, _parlays.p) AS r;

INSERT INTO parlay_legs
SELECT (jsonb_populate_record(NULL::parlay_legs, l || jsonb_build_object(
  'id', nextval('parlay_legs_id_seq'),
  'parlay_id', (SELECT new_id FROM _parlays WHERE old_id = (l->>'parlay_id')::int),
  'user_id', (SELECT new_id FROM _users WHERE old_id = l->>'user_id'),
  'game_id', (SELECT new_id FROM _games WHERE old_id = (l->>'game_id')::int),
  'placed_by_user_id', (SELECT new_id FROM _users WHERE old_id = l->>'placed_by_user_id'),
  'approval_by_user_id', (SELECT new_id FROM _users WHERE old_id = l->>'approval_by_user_id'),
  -- Suggestions aren't copied, so a leg can't point at one.
  'suggestion_id', NULL,
  -- Player ids differ between databases; the link is worked out again here.
  'player_id', NULL
))).*
FROM _in, jsonb_array_elements(doc->'legs') AS l;

-- What was loaded.
SELECT (SELECT name FROM leagues WHERE id = (SELECT new_id FROM _league)) AS league,
       (SELECT count(*) FROM _users) AS members,
       (SELECT count(*) FROM _parlays) AS parlays,
       (SELECT count(*) FROM parlay_legs WHERE parlay_id IN (SELECT new_id FROM _parlays)) AS parlay_legs,
       (SELECT count(*) FROM _weeks) AS weeks,
       (SELECT count(*) FROM _games) AS games;

COMMIT;
